"""检索层（M34）：向量 + 关键词/结构化 + 图谱（按需），三者各有分工。

为什么要一层"检索层"而不是继续在知识库/记忆里各写一套：

1. **一个查询要同时问三种信号**——字面（关键词精确命中）、语义（向量）、结构
   （谁调用谁/属于哪个符号/哪条契约）。谁强谁弱取决于问法，靠一个信号必然偏。
2. **元数据必须先过滤再排序**（filter-then-rank）。向量检索最坑的不是召回率，
   是"把不该看的也召回"：隔离区草稿、过期的、别的项目的。**先按元数据把候选裁到
   该看的集合，再在这个集合里排序**——精度问题在检索层解决，不靠提示词请求模型忽略。
3. **失效必须跟着内容走**：向量缓存按内容哈希存，内容变了旧向量自然不再被使用；
   而不是"文档改了向量还是老的"。

子模块：
- `metadata.py` 统一的分块元数据与过滤条件（来源、区域、标签、路径、符号、契约、时间）
- `embed.py`    本地优先的向量后端 + 按内容哈希的持久缓存（失败自动降级，不拖垮会话）
- `hybrid.py`   RRF 融合（只依赖名次，回避分数不可比）+ 字面精确命中置顶 + 归因
- `graph.py`    按需的图谱查询（反向调用链/依赖链，N 跳、带 文件:行，绝不无限展开）
"""
